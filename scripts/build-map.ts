// Pre-projects Natural Earth geography (via world-atlas, 1:50m) into static SVG path data.
// Run with `npm run map`; output is committed so the app ships no geo libraries.
import { readFileSync, writeFileSync } from 'node:fs'
import { geoMercator, geoPath, geoGraticule } from 'd3-geo'
import { feature } from 'topojson-client'
import type { Topology, GeometryCollection } from 'topojson-specification'
import type { Feature, Geometry } from 'geojson'

const WIDTH = 1200
const EXTENT = { west: 94.2, east: 141.8, north: 7.6, south: -11.6 }

const INDONESIA = '360'
const NEIGHBOURS = ['458', '096', '626', '598', '608', '702', '036', '764', '704', '116', '104']

const NODES = [
  { id: 'batam', name: 'Batam', lon: 104.05, lat: 1.13 },
  { id: 'surabaya', name: 'Surabaya', lon: 112.75, lat: -7.25 },
  { id: 'balikpapan', name: 'Balikpapan', lon: 116.83, lat: -1.27 },
  { id: 'sorong', name: 'Sorong', lon: 131.25, lat: -0.88 },
]

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8')) as Topology
const countries = feature(topo, topo.objects.countries as GeometryCollection) as unknown as {
  features: Feature<Geometry, { name: string }>[]
}

const projection = geoMercator()
const corners = [projection([EXTENT.west, EXTENT.north])!, projection([EXTENT.east, EXTENT.south])!]
const scale = WIDTH / (corners[1][0] - corners[0][0])
projection.scale(projection.scale() * scale).translate([0, 0])
const tl = projection([EXTENT.west, EXTENT.north])!
const br = projection([EXTENT.east, EXTENT.south])!
projection.translate([-tl[0], -tl[1]])
const HEIGHT = Math.round(br[1] - tl[1])
projection.clipExtent([[-2, -2], [WIDTH + 2, HEIGHT + 2]])

const path = geoPath(projection).digits(1)
const byId = (id: string) => countries.features.find((f) => String(f.id) === id)

const indonesia = path(byId(INDONESIA)!)!
const neighbours = NEIGHBOURS.map((id) => byId(id)).filter(Boolean).map((f) => path(f!)).filter(Boolean).join('')

const graticule = geoGraticule().extent([[90, -15], [145, 10]]).step([5, 5])
const graticulePath = path(graticule())!

const lonTicks = [95, 100, 105, 110, 115, 120, 125, 130, 135, 140].map((lon) => ({
  label: `${lon}°E`,
  x: Math.round(projection([lon, 0])![0] * 10) / 10,
}))
const latTicks = [5, 0, -5, -10].map((lat) => ({
  label: lat === 0 ? '0°' : `${Math.abs(lat)}°${lat > 0 ? 'N' : 'S'}`,
  y: Math.round(projection([100, lat])![1] * 10) / 10,
}))

const nodes = NODES.map((n) => {
  const [x, y] = projection([n.lon, n.lat])!
  return { ...n, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }
})

const out = `// GENERATED by scripts/build-map.ts — do not edit by hand.
// Geography: Natural Earth (public domain) via world-atlas 1:50m. Mercator projection.
export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}
export const INDONESIA_PATH = ${JSON.stringify(indonesia)}
export const NEIGHBOURS_PATH = ${JSON.stringify(neighbours)}
export const GRATICULE_PATH = ${JSON.stringify(graticulePath)}
export const LON_TICKS = ${JSON.stringify(lonTicks)}
export const LAT_TICKS = ${JSON.stringify(latTicks)}
export const NODE_POSITIONS = ${JSON.stringify(nodes, null, 2)} as const
`
writeFileSync('src/features/network-map/geo.generated.ts', out)
console.log(`map: ${WIDTH}x${HEIGHT}, indonesia ${indonesia.length} chars, neighbours ${neighbours.length} chars`)
