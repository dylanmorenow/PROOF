// Samples land points for the sign-in globe from Natural Earth (world-atlas 1:110m).
// Run with `node scripts/build-globe.ts`; output is committed so the app ships no geo libraries.
import { readFileSync, writeFileSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'
import type { Topology, GeometryCollection } from 'topojson-specification'
import type { Feature, FeatureCollection, Geometry } from 'geojson'

const N = 16000 // Fibonacci-sphere samples; roughly 29% land
const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8')) as Topology
const countries = feature(topo, topo.objects.countries as GeometryCollection) as unknown as FeatureCollection<Geometry>
const indonesia = countries.features.find((f) => String(f.id) === '360') as Feature<Geometry>

const land: number[] = []
const indo: number[] = []
const golden = Math.PI * (3 - Math.sqrt(5))
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2
  const lat = (Math.asin(y) * 180) / Math.PI
  const lon = ((((i * golden * 180) / Math.PI) % 360) + 360) % 360 - 180
  const p: [number, number] = [lon, lat]
  if (geoContains(indonesia, p)) continue
  if (countries.features.some((f) => geoContains(f, p))) land.push(+lat.toFixed(2), +lon.toFixed(2))
}

// Indonesia gets its own denser grid from the 1:50m data so the archipelago reads clearly.
const topo50 = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8')) as Topology
const indo50 = (feature(topo50, topo50.objects.countries as GeometryCollection) as unknown as FeatureCollection<Geometry>).features.find((f) => String(f.id) === '360') as Feature<Geometry>
for (let lat = -11; lat <= 6.5; lat += 0.55) {
  for (let lon = 95; lon <= 141.5; lon += 0.55) {
    if (geoContains(indo50, [lon, lat])) indo.push(+lat.toFixed(2), +lon.toFixed(2))
  }
}

writeFileSync(
  'src/features/landing/globe.generated.ts',
  `// GENERATED by scripts/build-globe.ts. Natural Earth land points as [lat, lon] pairs.
export const LAND = new Float32Array(${JSON.stringify(land)})
export const INDONESIA = new Float32Array(${JSON.stringify(indo)})
`,
)
console.log(`globe: ${land.length / 2} land points, ${indo.length / 2} Indonesia points`)
